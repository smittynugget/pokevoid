export let CHAMPION_DEFINITIONS: Record<string, Partial<PlayableChampionData>> = new Proxy({} as Record<string, Partial<PlayableChampionData>>, {
  get(target, prop: string | symbol) {
    const propKey = prop as string;

    if (propKey === "apollo" || propKey === "diana") {
      const baseKey = "apollo_diana";
      if (!_CHAMPION_DEFINITIONS) {
        initializeChampionDefinitions();
      }
      if (!(baseKey in target)) {
        target[baseKey] = _CHAMPION_DEFINITIONS[baseKey];
      }
      const baseDefinition = target[baseKey];
      if (!baseDefinition) return undefined;

      const uiOverrides = propKey === "apollo"
          ? { skillTreeRootOffsetX: -5, skillTreeRootOffsetY: -7 }
          : { previewScale: 0.61364, skillTreeRootOffsetX: 0, skillTreeRootOffsetY: -1, skillTreeTrainerBondOffsetX: 0 };

      return {
        ...baseDefinition,
        id: propKey,
        ui: {
          ...baseDefinition.ui,
          ...uiOverrides
        }
      };
    }

    if (!(propKey in target)) {
      if (!_CHAMPION_DEFINITIONS) {
        initializeChampionDefinitions();
      }
      target[propKey] = _CHAMPION_DEFINITIONS[propKey as keyof Record<string, Partial<PlayableChampionData>>];
    }
    return target[propKey];
  }
});

